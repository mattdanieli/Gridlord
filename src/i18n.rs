//! Traduzioni delle lingue aggiuntive. La chiave e il testo inglese scritto in gui.rs
//! (stesso testo, stessi segnaposto {0}, {1}...). Inglese e italiano stanno in gui.rs.
//!
//! Per aggiungere un testo: scrivilo in gui.rs con `t`/`l`/`f`, poi aggiungi la riga
//! con la stessa chiave in ogni tabella qui sotto (il test `ogni_testo_e_tradotto` lo controlla).

use std::collections::HashMap;
use std::sync::OnceLock;

use crate::gui::Lang;

pub fn get(lang: Lang, en: &str) -> Option<&'static str> {
    static MAPS: OnceLock<[HashMap<&'static str, &'static str>; 5]> = OnceLock::new();
    let maps = MAPS.get_or_init(|| [ZH, DE, ES, FR, RU].map(|t| t.iter().copied().collect()));
    let i = match lang {
        Lang::Zh => 0,
        Lang::De => 1,
        Lang::Es => 2,
        Lang::Fr => 3,
        Lang::Ru => 4,
        Lang::En | Lang::It => return None,
    };
    maps[i].get(en).copied()
}

